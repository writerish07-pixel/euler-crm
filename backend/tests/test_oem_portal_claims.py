def test_list_and_detail_stamps_are_the_same_instant():
    """The list is IST, the journey is UTC, and they are 5h30m apart.

    Reading one with the other's rule shifts every ageing figure by a day.
    """
    from_list = oem_claims.parse_list_datetime("2 Sep 2026 13:34:38")
    from_detail = oem_claims.parse_detail_datetime("2026-09-02 08:04:38")
    assert from_list is not None and from_detail is not None
    assert from_list == from_detail
    assert oem_claims.date_ist(from_list) == "2026-09-02"


