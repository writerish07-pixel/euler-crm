def _rows(n):
    return [list_row(f"n{i}", f"AF-999-CL{i:04d}") for i in range(n)]


def test_one_sweep_is_enough_when_it_returns_everything(monkeypatch):
    seen = []

    def fake(token, *, status="", limit=100, max_rows=5000):
        seen.append(status)
        return _rows(3), 3

    monkeypatch.setattr(coulson_client, "fetch_debit_notes", fake)
    monkeypatch.setattr(coulson_client, "fetch_claim_status_counts", lambda t, s="": {"a": 3})
    rows, mode, expected = oem_claims.fetch_all_claims("tok")
    assert len(rows) == 3 and mode == "sweep" and expected == 3
    assert seen == [""]


def test_a_short_sweep_falls_back_to_walking_every_status(monkeypatch):
    """If the API applies a default status filter, a plain sweep mirrors one bucket
    and silently drops the rest. The per-status walk is what stops that."""
    def fake(token, *, status="", limit=100, max_rows=5000):
        if not status:
            return _rows(2), 2
        return [list_row(f"s-{status}", f"AF-999-{status[:4]}")], 1

    monkeypatch.setattr(coulson_client, "fetch_debit_notes", fake)
    monkeypatch.setattr(coulson_client, "fetch_claim_status_counts",
                        lambda t, s="": {s: 1 for s in coulson_client.CLAIM_STATUSES})
    rows, mode, expected = oem_claims.fetch_all_claims("tok")
    assert mode == "per-status"
    assert expected == len(coulson_client.CLAIM_STATUSES)
    assert len(rows) > 2


